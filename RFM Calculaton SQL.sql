SELECT 'Customers' as table_name, COUNT(*) as record_count FROM customers
UNION ALL
SELECT 'Orders', COUNT(*) FROM orders;

SELECT 
    MIN(order_date) as earliest_order,
    MAX(order_date) as latest_order,
    COUNT(*) as total_orders
FROM orders;


SELECT 
    c.customer_id,
    c.customer_name,
    c.email,
    c.city,
    COUNT(o.order_id) as frequency,
    SUM(o.order_value) as monetary_value,
    MAX(o.order_date) as last_purchase_date,
    DATEDIFF(CURDATE(), MAX(o.order_date)) as recency_days
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name, c.email, c.city
ORDER BY monetary_value DESC;

SELECT 
    COUNT(DISTINCT customer_id) as total_customers,
    COUNT(DISTINCT CASE WHEN customer_status = 'Active' THEN customer_id END) as active_customers,
    COUNT(DISTINCT CASE WHEN customer_status = 'Inactive' THEN customer_id END) as inactive_customers,
    SUM(total_orders) as total_orders,
    SUM(total_revenue) as total_revenue
FROM (
    SELECT 
        c.customer_id,
        c.customer_status,
        COUNT(o.order_id) as total_orders,
        SUM(o.order_value) as total_revenue
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_id, c.customer_status
) summary_data;


SELECT 
    c.customer_id,
    c.customer_name,
    COUNT(o.order_id) as purchase_count,
    SUM(o.order_value) as total_spent
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name
ORDER BY purchase_count DESC;


SELECT 
    YEAR(order_date) as year,
    MONTH(order_date) as month,
    COUNT(DISTINCT customer_id) as unique_customers,
    COUNT(order_id) as order_count,
    SUM(order_value) as monthly_revenue,
    AVG(order_value) as avg_order_value
FROM orders
GROUP BY YEAR(order_date), MONTH(order_date)
ORDER BY year DESC, month DESC;

SELECT 
    c.customer_id,
    c.customer_name,
    c.city,
    COUNT(o.order_id) as total_orders,
    SUM(o.order_value) as total_revenue,
    AVG(o.order_value) as avg_order_value,
    MAX(o.order_date) as last_purchase
