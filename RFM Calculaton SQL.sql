    c.customer_id,
    c.customer_name,
    c.email,
    c.city,
    COUNT(o.order_id) as total_purchases,
    SUM(o.order_value) as lifetime_value,
    MAX(o.order_date) as last_purchase_date,
    DATEDIFF(CURDATE(), MAX(o.order_date)) as days_since_purchase
